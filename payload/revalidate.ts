/**
 * Скидання кешу сторінок після правки в адмінці.
 *
 * Без цього редактор зберігає зміну і бачить на сайті стару версію ще до
 * пʼяти хвилин (стільки живе ISR-кеш). Виглядає як «адмінка не працює», і
 * саме на цьому спіткнувся Бро, змінивши напис на кнопці.
 *
 * Скидаємо весь дерев'яний кеш від кореня: сайт невеликий, наскрізні дані
 * (телефони, меню, футер) стоять на кожній сторінці, тож точкове скидання
 * однаково зачепило б майже все — тільки з ризиком щось пропустити.
 *
 * `next/cache` імпортуємо динамічно й під try: сід і скрипти обслуговування
 * працюють поза Next, там revalidatePath не існує і кидає помилку.
 */
async function purgeCache() {
  try {
    const { revalidatePath } = await import('next/cache');
    revalidatePath('/', 'layout');
  } catch {
    // Поза середовищем Next скидати нічого — і це нормально.
  }
}

/** Для колекцій: afterChange і afterDelete. */
export const revalidateAfterChange = async () => {
  await purgeCache();
};

/** Для глобалів — сигнатура та сама, винесено окремо лише для читабельності. */
export const revalidateGlobal = async () => {
  await purgeCache();
};
