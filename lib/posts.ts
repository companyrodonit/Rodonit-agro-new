export type PostBlock =
  | { type: 'heading'; text: string }
  | { type: 'paragraph'; text: string }
  | { type: 'list'; items: string[] };

export type PostTag = { slug: string; label: string; kind: 'product' | 'culture' };

export type Post = {
  slug: string;
  title: string;
  excerpt: string;
  category: string;
  categorySlug: string;
  readMinutes: number;
  cover?: string;
  /**
   * Підпис до обкладинки. Заголовок статті як alt не годиться: він уже стоїть
   * поруч у <h1>, і для скрінрідера це просто повтор. Тут — що саме на фото.
   */
  coverAlt?: string;
  /** Дати публікації від замовника ще немає — див. коментар угорі файлу. */
  date?: string;
  /**
   * Автор матеріалу. Порожньо → автором вважається компанія.
   * Заповнюється в адмінці; у перенесених зі старого сайту статтях
   * авторства не було вказано, тому тут його немає.
   */
  author?: string;
  /**
   * Короткий заголовок для <title>, 50-60 символів.
   * title статей — журналістський, до 119 символів; Google обрізає ~60.
   * Порожньо → заголовок ріжеться по слову автоматично.
   */
  seoTitle?: string;
  /**
   * Опис для видачі, 150-160 символів. Порожньо → береться excerpt,
   * обрізаний по слову (він писався як анонс на картці, не як meta).
   */
  metaDescription?: string;
  tags: PostTag[];
  blocks: PostBlock[];
};

