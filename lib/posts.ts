/* ------------------------------------------------------------- селектори */

export const getPost = (slug: string) => posts.find((p) => p.slug === slug);

export const postsByCategory = (categorySlug: string) =>
  posts.filter((p) => p.categorySlug === categorySlug);

export const postsByTag = (tagSlug: string) =>
  posts.filter((p) => p.tags.some((t) => t.slug === tagSlug));

/** Усі теги з лічильником — для сторінок тегів і sitemap. */
export const allTags = Array.from(
  posts
    .flatMap((p) => p.tags)
    .reduce((acc, t) => {
      const prev = acc.get(t.slug);
      acc.set(t.slug, { ...t, count: (prev?.count ?? 0) + 1 });
      return acc;
    }, new Map<string, PostTag & { count: number }>())
    .values()
).sort((a, b) => b.count - a.count);

/**
 * Схожі матеріали: спершу ті, що ділять теги (більше спільних — вище),
 * далі добираємо з тієї ж категорії, щоб блок ніколи не був порожнім.
 */
export function relatedPosts(slug: string, limit = 3): Post[] {
  const post = getPost(slug);
  if (!post) return [];
  const tagSlugs = new Set(post.tags.map((t) => t.slug));

  const scored = posts
    .filter((p) => p.slug !== slug)
    .map((p) => ({ p, score: p.tags.filter((t) => tagSlugs.has(t.slug)).length }))
    .sort((a, b) => b.score - a.score || a.p.title.localeCompare(b.p.title));

  const picked = scored.filter((s) => s.score > 0).map((s) => s.p);
  if (picked.length >= limit) return picked.slice(0, limit);

  const filler = posts.filter(
    (p) => p.slug !== slug && !picked.includes(p) && p.categorySlug === post.categorySlug
  );
  return [...picked, ...filler].slice(0, limit);
}

/* ---------------------------------------------------- анкори підзаголовків */

const TRANSLIT: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'h', ґ: 'g', д: 'd', е: 'e', є: 'ie', ж: 'zh', з: 'z',
  и: 'y', і: 'i', ї: 'i', й: 'i', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p',
  р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'kh', ц: 'ts', ч: 'ch', ш: 'sh',
  щ: 'shch', ь: '', ю: 'iu', я: 'ia', ы: 'y', э: 'e', ъ: '',
};

/**
 * Латинський анкор із українського підзаголовка. Кириличний id у href
 * браузер percent-кодує, і посилання в TOC виглядає як %D0%9A%D0%BB... —
 * тому транслітеруємо, як і решта slug-ів у проєкті.
 */
export function headingSlug(text: string): string {
  return (
    text
      .toLowerCase()
      .split('')
      .map((ch) => (ch in TRANSLIT ? TRANSLIT[ch] : ch))
      .join('')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 60) || 'rozdil'
  );
}

/** Підзаголовки статті для змісту. */
export const postHeadings = (post: Post) =>
  post.blocks
    .filter((b): b is Extract<PostBlock, { type: 'heading' }> => b.type === 'heading')
    .map((b) => ({ id: headingSlug(b.text), text: b.text }));
