/* --------------------------------------------------- дизайн-блоки через маркери
 *
 * Схема Payload лишається як є: маркер — це звичайний абзац, який починається
 * з [[...]]. Так Олег може вставити картку препарату прямо в адмінці, а нам не
 * треба міняти колекцію (drizzle push на прод-базі — окрема пригода).
 *
 * Синтаксис:
 *   [[product:nordoks]]              — картка препарату (дані з каталогу)
 *   [[rates:nordoks]]                — уся таблиця регламенту препарату
 *   [[rates:nordoks:буряк]]          — тільки рядки про цю культуру
 *   [[callout]] Текст                — виноска «Важливо»
 *   [[callout:Свій заголовок]] Текст
 *   [[faq]] Питання? | Відповідь     — пункт акордеона + FAQPage schema
 *   [[table]] Шапка | Шапка          — довільна таблиця, перший рядок — шапка,
 *   Комірка | Комірка                  далі по рядку на новий рядок тексту
 *   [[table:Підпис]] …               — те саме з підписом над таблицею
 */

export type PostMarker =
  | { kind: 'product'; slug: string }
  | { kind: 'rates'; slug: string; filter?: string }
  | { kind: 'callout'; title: string; text: string }
  | { kind: 'faq'; question: string; answer: string }
  | { kind: 'table'; caption?: string; head: string[]; rows: string[][] };

const MARKER_RE = /^\[\[([a-z]+)(?::([^\]]+))?\]\]\s*([\s\S]*)$/;

/**
 * Розбирає абзац-маркер. Повертає null для звичайного тексту — і для маркера,
 * заповненого неправильно: краще показати абзац як є, ніж вирізати контент.
 */
export function parseMarker(text: string): PostMarker | null {
  const m = MARKER_RE.exec(text.trim());
  if (!m) return null;
  const [, kind, arg, rest] = m;

  switch (kind) {
    case 'product':
      return arg ? { kind, slug: arg.trim() } : null;
    case 'rates': {
      if (!arg) return null;
      // Другий сегмент — фільтр по культурі: у статті про буряк не потрібні
      // всі двадцять рядків регламенту, потрібен свій.
      const [slug, filter] = arg.split(':');
      return slug.trim()
        ? { kind, slug: slug.trim(), ...(filter?.trim() && { filter: filter.trim() }) }
        : null;
    }
    case 'callout':
      return rest.trim() ? { kind, title: arg?.trim() || 'Важливо', text: rest.trim() } : null;
    case 'faq': {
      const [question, ...answer] = rest.split('|');
      const a = answer.join('|').trim();
      return question.trim() && a ? { kind, question: question.trim(), answer: a } : null;
    }
    case 'table': {
      // Рядок таблиці — рядок тексту, комірки через «|». Крайні труби
      // необовʼязкові: редактор може скопіювати таблицю з markdown як є.
      const cells = (line: string) =>
        line.replace(/^\s*\|/, '').replace(/\|\s*$/, '').split('|').map((c) => c.trim());
      const lines = rest.split('\n').map((l) => l.trim()).filter(Boolean);
      if (lines.length < 2) return null;
      const head = cells(lines[0]);
      const rows = lines
        .slice(1)
        // Рядок-роздільник markdown (|---|---|) шапку не дублює, він службовий.
        .filter((l) => !/^[\s|:-]+$/.test(l))
        .map(cells)
        .filter((r) => r.some(Boolean));
      if (head.length < 2 || !rows.length) return null;
      return { kind, head, rows, ...(arg?.trim() && { caption: arg.trim() }) };
    }
    default:
      return null;
  }
}

/**
 * Питання-відповіді статті — для FAQPage schema.
 * Порожній масив означає «секції немає»: FAQPage без питань Google рахує
 * битою розміткою, тому на сторінці його тоді не рендеримо взагалі.
 */
export const postFaq = (post: Post): { question: string; answer: string }[] =>
  post.blocks.flatMap((b) => {
    if (b.type !== 'paragraph') return [];
    const marker = parseMarker(b.text);
    return marker?.kind === 'faq' ? [{ question: marker.question, answer: marker.answer }] : [];
  });
