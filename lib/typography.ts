/**
 * Дрібна типографіка для текстів, які приходять із CMS.
 */

/** Word joiner U+2060 — нульова ширина, забороняє перенос у цьому місці. */
const WJ = '⁠';

/**
 * Коса риска між двома короткими буквеними токенами: «кг/га», «л/т», «г/кг»,
 * «Cu/га», «мг/л». Обидві частини не довші за 3 символи — цього досить, щоб
 * зачепити всі одиниці виміру й не зачепити нічого іншого.
 *
 * Числові дроби («1/10–1/4 обʼєму») не підпадають: там цифри, не літери.
 * Схеми URL теж — перед «//» стоїть двокрапка, а не літера.
 */
const UNIT_SLASH = /([\p{L}µ²³]{1,3})\/(?!\/)([\p{L}µ²³]{1,3})/gu;

/**
 * Забороняє переносити рядок усередині одиниці виміру.
 *
 * Навіщо: за правилами переносу коса риска — законне місце розриву, тож на
 * мобільному «1,0–3,0 кг/га» розпадається на «кг/» і «га». Заміряно 11.08
 * на 390px: 35 таких випадків на 13 сторінках, причому найгустіше — у
 * таблицях норм витрати, тобто рівно там, де аграрій читає цифри.
 *
 * Word joiner, а не `<span class="whitespace-nowrap">`: тексти приходять із
 * CMS звичайними рядками й рендеряться як текст у десятку різних місць.
 * Обгортка вимагала б розбивати рядок на масив React-вузлів у кожному з них.
 *
 * ⚠️ Тільки для того, що видно на екрані. У JSON-LD, meta description і
 * sitemap подавати ЧИСТИЙ рядок: невидимий символ у структурованих даних —
 * це сміття, яке потім спливе в чужому парсері.
 */
export function keepUnits(text: string): string {
  return text
    .replace(UNIT_SLASH, `$1/${WJ}$2`)
    .replace(NUM_RANGE, `$1$2${WJ}$3`)
    .replace(NUM_UNIT, `$1${NBSP}`);
}

/** Нерозривний пробіл U+00A0. */
const NBSP = '\u00a0';

/**
 * Діапазон чисел «0,2–0,5», «1-4»: після тире чи дефіса браузер має право
 * перенести рядок, і на мобільному норма розпадається на «0,2–» і «0,5 кг/га».
 * Заміряно 08.10 на 360/390/1440 у FAQ статей блогу.
 */
const NUM_RANGE = /(\d)([–-])(\d)/g;

/**
 * Число й одиниця виміру після нього: «0,5 кг/га», «300 г/кг», «1,2 мкм».
 * Lookahead на не-літеру після одиниці — щоб «5 гілок» чи «3 тижні» не чіпати.
 */
const NUM_UNIT = /(\d) (?=(?:кг|г|л|мл|т|га|мкм|мм|см)(?!\p{L}))/gu;
